/**
 * CPU-side reference for shader's intensity normalization.
 * Clamps to [0, 1]. Returns 0 if min >= max (degenerate range).
 */
export function normalizeIntensity(x: number, min: number, max: number): number {
  if (max <= min) return 0;
  const t = (x - min) / (max - min);
  return Math.max(0, Math.min(1, t));
}

/**
 * Color mode uniform — serializes to GPU-ready byte layout.
 * Layout: { min: f32, max: f32, mode: u32, _pad: u32 } = 16 bytes.
 * std140-compatible alignment.
 */
export class ColorModeUniform {
  constructor(
    public min: number,
    public max: number,
    public mode: ColorMode,
  ) {}

  toArrayBuffer(): ArrayBuffer {
    const buf = new ArrayBuffer(16);
    const f32 = new Float32Array(buf);
    const u32 = new Uint32Array(buf);
    f32[0] = this.min;
    f32[1] = this.max;
    u32[2] = this.mode;
    // u32[3] = 0 (padding, default-initialized)
    return buf;
  }
}

